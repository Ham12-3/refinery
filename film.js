function setupScrollAnimations() {
  const split = (el, type = 'lines') => SplitText.create(el, { type, mask: 'lines', linesClass: 'line' });

  // Hero: title rises in letter by letter, then drifts up and out as you scroll
  const title = split('.hero-title', 'chars,lines');
  const heroCopy = split('.hero-meta, .hero-lede');
  if (reduced) return;
  gsap.timeline({ delay: 0.25 })
    .from(title.chars, { yPercent: 105, duration: 1.5, ease: 'expo.out', stagger: 0.045 })
    .from(heroCopy.lines, { yPercent: 105, duration: 1.1, ease: 'expo.out', stagger: 0.06 }, 0.45)
    .from('.scroll-hint', { opacity: 0, duration: 1 }, 0.9);
  gsap.to('.hero-title', { yPercent: -45, ease: 'none', scrollTrigger: { trigger: '.hero', start: 'top top', end: 'bottom top', scrub: true } });
  gsap.to('.hero-meta, .hero-lede, .scroll-hint', { opacity: 0, y: -30, ease: 'none', scrollTrigger: { trigger: '.hero', start: 'top top', end: '45% top', scrub: true } });

  // Chapters: heading and body lines unmask on entry, reverse on exit; progress rule is scrubbed
  chapterEls.forEach((sec) => {
    const h = split(sec.querySelector('h2'));
    const body = split(sec.querySelector('.ch-body'));
    const tl = gsap.timeline({ paused: true })
      .from(sec.querySelector('.ch-index'), { opacity: 0, y: 10, duration: 0.6, ease: 'power2.out' })
      .from(h.lines, { yPercent: 110, duration: 1.1, ease: 'expo.out', stagger: 0.08 }, 0.05)
      .from(body.lines, { yPercent: 110, duration: 1, ease: 'expo.out', stagger: 0.035 }, 0.2)
      .from(sec.querySelectorAll('.ch-list li'), { opacity: 0, y: 14, duration: 0.7, ease: 'power3.out', stagger: 0.06 }, 0.45)
      .from(sec.querySelector('.ch-progress'), { scaleX: 0, transformOrigin: 'left', duration: 0.9, ease: 'expo.out' }, 0.5);
    ScrollTrigger.create({
      trigger: sec, start: 'top 55%', end: 'bottom 45%',
      onToggle: (self) => (self.isActive ? tl.timeScale(1).play() : tl.timeScale(2.2).reverse()),
    });
    gsap.to(sec.querySelector('.ch-progress i'), { scaleX: 1, ease: 'none', scrollTrigger: { trigger: sec, start: 'top top', end: 'bottom bottom', scrub: true } });
  });

  // Outro
  const outroTitle = split('.outro-title');
  gsap.timeline({ scrollTrigger: { trigger: '.outro', start: 'top 60%', toggleActions: 'play none none reverse' } })
    .from(outroTitle.lines, { yPercent: 110, duration: 1.2, ease: 'expo.out', stagger: 0.08 })
    .from('.outro .ch-index', { opacity: 0, duration: 0.6 }, 0)
    .from('.outro-list li', { opacity: 0, y: 24, duration: 0.8, ease: 'power3.out', stagger: 0.05 }, 0.25)
    .from('#replay', { opacity: 0, duration: 0.6 }, 0.7);
}

