/* ------------------------------------------------------------------ Loading */
const images = new Array(FRAME_COUNT);
let loadedCount = 0;
function loadFrame(i) {
  return new Promise((resolve) => {
    const img = new Image();
    img.decoding = 'async';
    const done = () => {
      loadedCount++;
      $('#loader-n').textContent = loadedCount;
      $('#loader-fill').style.width = `${(loadedCount / FRAME_COUNT) * 100}%`;
      resolve();
    };
    img.onload = () => { images[i] = img; done(); };
    img.onerror = done;
    img.src = `frames/${quality}/f_${String(i + 1).padStart(3, '0')}.webp`;
  });
}
async function loadAll() {
  let next = 0;
  const worker = async () => { while (next < FRAME_COUNT) await loadFrame(next++); };
  await Promise.all(Array.from({ length: 10 }, worker));
}

function smoothTrack(arr, win = 2) {
  return arr.map((p, i) => {
    if (!p) return null;
    let sx = 0, sy = 0, n = 0;
    for (let k = -win; k <= win; k++) {
      const q = arr[i + k];
      if (q) { sx += q[0]; sy += q[1]; n++; }
    }
    return [sx / n, sy / n];
  });
}

