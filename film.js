let tracks = null;
let frameF = 0, shownIdx = -1, vel = 0, introStart = 0, lastCh = -1;
const tilt = { x: 0, y: 0 };
const v3 = new THREE.Vector3();
const frameN = $('#frame-n');
const progressFill = $('#progress-fill');
const navBtns = $$('[data-go]');
const easeOut = (t) => 1 - Math.pow(1 - t, 4);

function trackAt(id, f) {
  const t = tracks[id];
  const i = Math.floor(f), j = Math.min(i + 1, FRAME_COUNT - 1), k = f - i;
  const a = t[i], b = t[j];
  if (!a && !b) return null;
  if (!a) return k > 0.5 ? b : null;
  if (!b) return k < 0.5 ? a : null;
  return [a[0] + (b[0] - a[0]) * k, a[1] + (b[1] - a[1]) * k];
}

function tick(now) {
  requestAnimationFrame(tick);
  const W = innerWidth, H = innerHeight, y = scrollY;
  const time = now / 1000;

  const targetF = frameForScroll(y);
  frameF = reduced ? targetF : lerp(frameF, targetF, 0.18);
  if (Math.abs(frameF - targetF) < 0.002) frameF = targetF;
  const idx = clamp(Math.round(frameF), 0, FRAME_COUNT - 1);
  if (idx !== shownIdx && images[idx]) {
    frameTex.image = images[idx];
    frameTex.needsUpdate = true;
    shownIdx = idx;
  }
  vel = lerp(vel, clamp(Math.abs(targetF - frameF) / 10, 0, 1), 0.1);

  const box = boxAt(y + H * 0.5);
  const ch = box.ch;
  const inOutro = box.s.classList.contains('outro');
  if (ch !== lastCh) {
    lastCh = ch;
    document.body.classList.toggle('in-chapter', !!ch);
    navBtns.forEach((b) => b.classList.toggle('on', +b.dataset.go === ch));
  }

  const intro = introStart ? (reduced ? 1 : easeOut(clamp((now - introStart) / 2400, 0, 1))) : 0;
  const heroP = clamp(y / H, 0, 1);

  tilt.x = lerp(tilt.x, mouse.ny * 0.04, 0.05);
  tilt.y = lerp(tilt.y, mouse.nx * 0.07, 0.05);
  rig.rotation.set(tilt.x, tilt.y, 0);
  // Intro pulls back from a close crop; scrolling out of the hero eases slightly closer
  const zoom = 1 - (1 - intro) * 0.12 - heroP * 0.035;
  camera.position.set(-tilt.y * 1.1, tilt.x * 0.7, baseDist * zoom - vel * 0.4);
  camera.lookAt(0, 0, 0);

  planeMat.uniforms.uVel.value = vel;
  planeMat.uniforms.uFade.value = intro;
  planeMat.uniforms.uDim.value = lerp(planeMat.uniforms.uDim.value, inOutro ? 1 : 0, 0.05);
  scene.updateMatrixWorld();

  if (tracks) {
    const mobile = mqMobile.matches;
    // Callouts that would sit on top of the chapter copy are hidden
    const copy = ch && !mobile ? box.s.querySelector('.ch-text').getBoundingClientRect() : null;
    const measure = [];
    // Pass 1: place every trackable marker and project its callout end point
    for (const l of LABELS) {
      const primary = l.chapter === ch || (l.also || []).includes(ch);
      const p = ch && !inOutro && (!mobile || primary) ? trackAt(l.id, frameF) : null;
      l.live = !!p && p[0] > 0.02 && p[0] < 0.98 && p[1] > 0.04 && p[1] < 0.96;
      if (!l.live) continue;
      const px = (p[0] - 0.5) * PW, py = (0.5 - p[1]) * PH;
      l.g.position.set(px, py, curveZ(px) + 0.01);

      const hot = hotId === l.id || openLabel === l;
      const compact = !primary && !hot;
      if (compact !== l.compact) { l.compact = compact; l.el.classList.toggle('compact', compact); l.w = 0; }
      l.el.classList.toggle('hot', hot);
      l.hot = hot;

      const s = mobile ? 0.6 : compact ? 0.8 : 1;
      l.end.set(l.off[0] * s, l.off[1] * s, l.off[2] * s);
      const pos = l.line.geometry.attributes.position;
      pos.setXYZ(1, l.end.x * 0.12, l.end.y, l.end.z * 0.6);
      pos.setXYZ(2, l.end.x, l.end.y, l.end.z);
      pos.needsUpdate = true;

      l.g.updateMatrixWorld();
      v3.set(0, 0, 0);
      l.g.localToWorld(v3).project(camera);
      l.ax = (v3.x * 0.5 + 0.5) * W;
      l.ay = (-v3.y * 0.5 + 0.5) * H;
      v3.copy(l.end);
      l.g.localToWorld(v3).project(camera);
      l.sx = (v3.x * 0.5 + 0.5) * W;
      l.sy = (-v3.y * 0.5 + 0.5) * H;
      if (!l.w) measure.push(l);
    }
    for (const l of measure) { l.w = l.el.offsetWidth; l.h = l.el.offsetHeight; }

    // Pass 2: resolve screen boxes, hide anything that collides with the chapter copy or an
    // earlier callout (primary callouts claim space first), then fade
    const placed = [];
    const order = [...LABELS].sort((a, b) => (a.compact === b.compact ? 0 : a.compact ? 1 : -1));
    for (const l of order) {
      let want = 0;
      if (l.live) {
        const left = l.off[0] < 0;
        l.x = clamp(left ? l.sx - l.w : l.sx, 12, W - l.w - 12);
        l.y = clamp(l.sy - l.h, 84, H - l.h - 50);
        const hit = (x0, y0, x1, y1) => copy && x0 < copy.right + 20 && x1 > copy.left - 20 && y0 < copy.bottom + 20 && y1 > copy.top - 20;
        const clash = placed.some((o) => l.x < o.x + o.w + 8 && l.x + l.w + 8 > o.x && l.y < o.y + o.h + 4 && l.y + l.h + 4 > o.y);
        want = clash || hit(l.x, l.y, l.x + l.w, l.y + l.h) || hit(l.ax - 12, l.ay - 12, l.ax + 12, l.ay + 12) ? 0 : 1;
        if (want) placed.push(l);
      }
      l.alpha = lerp(l.alpha, want * intro, want ? 0.12 : 0.25);
      const on = l.alpha > 0.01 && l.live;
      l.g.visible = on;
      l.el.style.visibility = on ? 'visible' : 'hidden';
      if (!on) continue;

      const pulse = (time * 0.6 + +l.idx * 0.17) % 1;
      const base = l.hot ? 1.6 : l.compact ? 0.75 : 1.1;
      l.ring.scale.setScalar(base);
      l.ping.scale.setScalar(base * (1 + pulse * 2));
      l.ping.material.opacity = l.alpha * (1 - pulse) * 0.6;
      l.ring.material.opacity = l.alpha;
      l.core.material.opacity = l.alpha;
      l.line.material.opacity = l.alpha * (l.compact ? 0.4 : 0.75);

      const rise = (1 - l.alpha) * 10;
      l.el.style.transform = `translate3d(${l.x.toFixed(1)}px, ${(l.y + rise).toFixed(1)}px, 0)`;
      l.el.style.opacity = l.alpha.toFixed(3);
      l.el.style.setProperty('--a', l.alpha.toFixed(3));
    }
  }

  frameN.textContent = String(idx).padStart(3, '0');
  const max = document.documentElement.scrollHeight - H;
  progressFill.style.transform = `scaleX(${clamp(y / max, 0, 1)})`;

  renderer.render(scene, camera);
}

