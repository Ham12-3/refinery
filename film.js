let boxes = [];
function layoutSections() {
  chapterEls.forEach((s) => {
    const span = +s.dataset.f1 - +s.dataset.f0;
    s.style.height = `${Math.max(200, span * (mqMobile.matches ? 4.2 : 3.6))}vh`;
  });
  boxes = sections.map((s) => ({ s, top: s.offsetTop, h: s.offsetHeight, f0: +s.dataset.f0, f1: +s.dataset.f1, ch: +(s.dataset.ch || 0) }));
}
function frameForScroll(y) {
  for (const b of boxes) if (y < b.top + b.h) return b.f0 + clamp((y - b.top) / b.h, 0, 1) * (b.f1 - b.f0);
  return FRAME_COUNT - 1;
}
const boxAt = (y) => boxes.find((b) => y < b.top + b.h) || boxes[boxes.length - 1];
function scrollForFrame(f, ch) {
  const b = boxes.find((x) => x.ch === ch && f >= x.f0 && f <= x.f1) || boxes.find((x) => x.ch && f >= x.f0 && f <= x.f1);
  return b ? b.top + ((f - b.f0) / (b.f1 - b.f0)) * b.h + 2 : 0;
}

